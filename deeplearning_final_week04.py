print(f"{'─'*60}")

t0 = time.time()
optimizer  = get_optimizer(model, stage=1)
scheduler  = CosineAnnealingLR(optimizer, T_max=CFG["epochs"], eta_min=1e-6)

for epoch in range(1, CFG["epochs"] + 1):

    if epoch == STAGE1_EPOCHS + 1:
        print(f"\n  ── Unfreezing backbone (Stage 2) ──")
        for param in model.parameters():
            param.requires_grad = True
        optimizer = get_optimizer(model, stage=2)
        scheduler = CosineAnnealingLR(optimizer, T_max=STAGE2_EPOCHS, eta_min=1e-6)
        print(f"  Trainable params: {sum(p.numel() for p in model.parameters() if p.requires_grad):,}\n")

    tr_loss, tr_acc = train_one_epoch(optimizer)
    vl_loss, vl_acc, vl_f1, vl_preds, vl_labels = evaluate()
    current_lr = optimizer.param_groups[0]["lr"]
    scheduler.step()

    stage = 1 if epoch <= STAGE1_EPOCHS else 2
    history["train_loss"].append(tr_loss)
    history["val_loss"].append(vl_loss)
    history["train_acc"].append(tr_acc)
    history["val_acc"].append(vl_acc)
    history["val_f1"].append(vl_f1)
    history["lr"].append(current_lr)
    history["stage"].append(stage)

    marker = " ←" if vl_acc > best_val_acc else ""
    if vl_acc > best_val_acc:
        best_val_acc = vl_acc
        best_preds, best_labels = vl_preds[:], vl_labels[:]
        torch.save({"model_state": model.state_dict(), "val_acc": vl_acc,
                    "val_f1": vl_f1, "classes": class_names, "config": CFG}, ckpt_path)

    print(f"  [{stage}] ep{epoch:2d}/{CFG['epochs']}  "
          f"tr={tr_acc:.4f}  vl={vl_acc:.4f}  f1={vl_f1:.4f}  "
          f"lr={current_lr:.1e}{marker}")

elapsed = time.time() - t0
